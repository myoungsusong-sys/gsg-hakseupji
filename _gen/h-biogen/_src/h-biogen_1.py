def transcribe(template_3to5):
    """3′→5′ 로 적은 주형 가닥 → 5′→3′ mRNA"""
    m = {'A': 'U', 'T': 'A', 'G': 'C', 'C': 'G'}
    return ''.join(m[b] for b in template_3to5)


