# 비분리 풀이기 — 성염색체 구성이 주어진 부모가 한 번의 비분리(감수 1분열 또는 2분열)로 만들 수 있는 생식세포
def nd_gametes(chs, nd):
    if nd is None:
        return {(c,) for c in chs}
    if nd == 'MI':
        return {tuple(sorted(chs)), ()}
    out = set()
    for c in chs:                      # 감수 2분열에서 c 를 가진 세포가 비분리
        out |= {(c, c), ()}
    return out


def nd_find(mother, father, ok):
    res = set()
    for who in ('모', '부'):
        for st in ('MI', 'MII'):
            eggs = nd_gametes(mother, st if who == '모' else None)
            sps = nd_gametes(father, st if who == '부' else None)
            for e in eggs:
                for s_ in sps:
                    if len(e) + len(s_) != 2 and ok(e + s_):   # 비분리가 결과에 드러난 경우만
                        res.add((who, st))
    return res


