MODES = ('AD', 'AR', 'XD', 'XR')   # 상염색체 우성·열성, X 염색체 우성·열성


def _opts(mode, sex):
    if mode[0] == 'A' or sex == 'F':
        return [(0, 0), (0, 1), (1, 1)]
    return [(0,), (1,)]


def _aff(mode, g):
    return sum(g) >= 1 if mode[1] == 'D' else sum(g) == len(g)


def _enum(people, mode, cons):
    out = []

    def rec(i, G, w, fk):
        if i == len(people):
            out.append((fk, w, dict(G)))
            return
        nm, sex, fa, mo, aff = people[i]
        if fa is None:
            opts, founder = [(g, Fr(1)) for g in _opts(mode, sex)], True
        else:
            dd = collections.defaultdict(Fr)
            gf, gm = G[fa], G[mo]
            for am in gm:
                pm = Fr(1, len(gm))
                if mode[0] == 'A':
                    for af in gf:
                        dd[tuple(sorted((af, am)))] += pm * Fr(1, len(gf))
                elif sex == 'F':
                    dd[tuple(sorted((gf[0], am)))] += pm
                else:
                    dd[(am,)] += pm
            opts, founder = list(dd.items()), False
        for g, p in opts:
            if aff is not None and _aff(mode, g) != aff:
                continue
            if cons and nm in cons and not cons[nm](g):
                continue
            G[nm] = g
            rec(i + 1, G, w * p, fk + ((nm, g),) if founder else fk)
            del G[nm]
    rec(0, {}, Fr(1), ())
    return out


def ped_modes(people, cons=None, modes=MODES):
    """모순 없이 설명되는 유전 방식 목록"""
    return [m for m in modes if _enum(people, m, cons)]


def ped_prob(people, mode, event, cons=None):
    """관찰(표현형·조건)이 주어졌을 때 event(G) 의 조건부 확률.
    가계도 밖에서 들어온 사람(창시자)의 유전자형이 확률에 영향을 주면(값이 둘 이상) 문제 불량 → assert."""
    rs = _enum(people, mode, cons)
    assert rs, ('모순', mode)
    by = collections.defaultdict(lambda: [Fr(0), Fr(0)])
    for fk, w, G in rs:
        by[fk][0] += w
        if event(G):
            by[fk][1] += w
    vals = {v[1] / v[0] for v in by.values()}
    assert len(vals) == 1, ('창시자 유전자형에 따라 값이 달라짐', mode, vals)
    return vals.pop()


def child_prob(people, mode, fa, mo, want, sex=None, cons=None):
    """fa·mo 사이에서 새로 태어날 아이가 want(발현 True / 정상 False) 일 확률.
    sex=None 이면 성별 모름(아들·딸 1/2씩), 'M'/'F' 면 그 성별일 때의 확률(조건부),
    'M&' / 'F&' 면 ‘그 성별이면서’ 의 확률(= 1/2 × 조건부)."""
    def one(sx):
        pp = people + [('_C', sx, fa, mo, None)]
        return ped_prob(pp, mode, lambda G: _aff(mode, G['_C']) == want, cons)
    if sex is None:
        return Fr(1, 2) * one('M') + Fr(1, 2) * one('F')
    if sex in ('M', 'F'):
        return one(sex)
    return Fr(1, 2) * one(sex[0])


def carrier(nm):
    """형질 대립유전자를 1개 이상 가짐"""
    return lambda G: sum(G[nm]) >= 1


def hetero(nm):
    return lambda G: len(G[nm]) == 2 and sum(G[nm]) == 1


