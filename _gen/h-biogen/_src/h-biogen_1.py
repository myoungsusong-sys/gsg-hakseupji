def ms(gen, start='H', medium='L'):
    """메셀슨-스탈: 가닥 표지 목록으로 복제를 흉내 내어 밀도별 DNA 수를 센다."""
    mols = [(start, start)]
    for _ in range(gen):
        nx = []
        for a, b in mols:
            nx += [(a, medium), (b, medium)]
        mols = nx
    cnt = collections.Counter(''.join(sorted(m)) for m in mols)
    return cnt, collections.Counter(s for m in mols for s in m)


