def poly(*parents):
    """다인자(더하기) — 각 부모의 생식세포별 대문자 수 분포를 합쳐 자손의 대문자 수 분포"""
    tot = collections.Counter({0: Fr(1)})
    for gam in parents:
        nxt = collections.Counter()
        for a, pa in tot.items():
            for b, pb in gam.items():
                nxt[a + b] += pa * pb
        tot = nxt
    return tot


def gam_ind(*pairs):
    """독립인 대립유전자 쌍들(예: 'Aa','BB') → 생식세포의 대문자 수 분포"""
    d = collections.Counter({0: Fr(1)})
    for pr in pairs:
        nxt = collections.Counter()
        for k, v in d.items():
            for al in pr:
                nxt[k + al.isupper()] += v * Fr(1, len(pr))
        d = nxt
    return d


