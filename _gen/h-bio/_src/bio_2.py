def _gts(mode, sex):
    if mode in ('AD', 'AR') or sex == 'F':
        return ['AA', 'Aa', 'aa']
    return ['A', 'a']

def _aff(mode, g):
    if mode in ('AD', 'XD'):
        return 'A' in g
    return 'A' not in g

def _can_child(mode, fg, mg, cg, csex):
    if mode in ('AD', 'AR'):
        return any(sorted(x + y) == sorted(cg) for x in fg for y in mg)
    if csex == 'M':
        return any(y == cg for y in mg)
    return any(sorted(fg + y) == sorted(cg) for y in mg)

def ped_modes(people, trios, extra=None):
    """people: {id: (sex 'M'/'F', affected bool)}, trios: [(father, mother, child)] → 가능한 유전 방식 목록"""
    ok = []
    ids = list(people)
    for mode in ('AD', 'AR', 'XD', 'XR'):
        opts = [[g for g in _gts(mode, people[i][0]) if _aff(mode, g) == people[i][1]] for i in ids]
        found = False
        for combo in itertools.product(*opts):
            G = dict(zip(ids, combo))
            if extra and not extra(mode, G):
                continue
            if all(_can_child(mode, G[f], G[m], G[c], people[c][0]) for f, m, c in trios):
                found = True; break
        if found:
            ok.append(mode)
    return ok

