def fs(x):
    """분수 → '1/4' 꼴 문자열"""
    x = Fr(x)
    return str(x.numerator) if x.denominator == 1 else f'{x.numerator}/{x.denominator}'


def dec(x):
    """Fraction/float → 깔끔한 소수 문자열 (0.4, 1.92, 2)"""
    s = f'{float(x):.4f}'.rstrip('0').rstrip('.')
    return s


def um(x):
    """길이(μm) 표기: 소수 첫째 자리까지 떨어지면 1자리 고정(3.0, 1.0), 아니면 dec"""
    x = Fr(x)
    return f'{float(x):.1f}' if (x * 10).denominator == 1 else dec(x)


# ── 유전 검산 도구 ─────────────────────────────────────────
def _gam(gt):
    pairs = [gt[i:i + 2] for i in range(0, len(gt), 2)]
    return [''.join(c) for c in itertools.product(*pairs)]


def cross(g1, g2):
    """상염색체 유전자형 문자열(예: 'AaBb') 두 개의 교배 → {자손 유전자형: 확률}"""
    out = collections.Counter()
    G1, G2 = _gam(g1), _gam(g2)
    for a in G1:
        for b in G2:
            ch = ''.join(''.join(sorted(x + y, key=lambda c: (c.lower(), c.islower()))) for x, y in zip(a, b))
            out[ch] += 1
    n = len(G1) * len(G2)
    return {k: Fr(v, n) for k, v in out.items()}


def P(dist, pred):
    return sum((p for k, p in dist.items() if pred(k)), Fr(0))


def dom(gt, i):
    """i번째 유전자 쌍에 대문자(우성)가 있는가"""
    return any(c.isupper() for c in gt[2 * i:2 * i + 2])


def abo_cross(f, m):
    """ABO 유전자형 'AO','BO' 등 → {혈액형: 확률}"""
    out = collections.Counter()
    for a in f:
        for b in m:
            s = set(a + b) - {'O'}
            bt = 'AB' if s == {'A', 'B'} else ('A' if s == {'A'} else ('B' if s == {'B'} else 'O'))
            out[bt] += Fr(1, 4)
    return out


def x_cross(fx, mx):
    """X 연관: 아버지 X 대립유전자 fx(문자 1개), 어머니 대립유전자 mx(문자 2개) → [(성별, 유전자형, 확률)]"""
    out = []
    for a in mx:
        out.append(('딸', ''.join(sorted(fx + a, key=lambda c: c.islower())), Fr(1, 4)))
        out.append(('아들', a, Fr(1, 4)))
    return out


