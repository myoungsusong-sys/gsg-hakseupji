def 본(p):
    return '\n'.join(p)


def 표(p):
    lab = '가나다라마바'
    return '\n'.join(f'({lab[i]}) {x}' for i, x in enumerate(p))


def 두(p):
    가, 나 = p
    return f'(가)\n{본(가)}\n\n(나)\n{본(나)}'


def 고(p, *pairs):
    t = p if isinstance(p, str) else (두(p) if isinstance(p, tuple) else 본(p))
    for old, new in pairs:
        assert t.count(old) == 1, (old, t.count(old))
        t = t.replace(old, new)
    return t


