def light_nc(h2o):
    """비순환적 전자 흐름: H₂O n분자 → 전자 2n개 → O₂ n/2, NADPH n"""
    e = 2 * h2o
    return dict(e=e, O2=Fr(h2o, 2), NADPH=Fr(e, 2))


def calvin(co2):
    """CO₂ n분자 고정 → 3PG 2n, G3P 2n, 방출 G3P n/3, 재생 RuBP n, ATP 3n, NADPH 2n"""
    return dict(PG3=2 * co2, G3P=2 * co2, out=Fr(co2, 3), regen_G3P=2 * co2 - Fr(co2, 3),
                RuBP=co2, ATP=3 * co2, NADPH=2 * co2)


assert light_nc(6) == dict(e=12, O2=3, NADPH=6)
assert calvin(3) == dict(PG3=6, G3P=6, out=1, regen_G3P=5, RuBP=3, ATP=9, NADPH=6)
assert calvin(6)['ATP'] == 18 and calvin(6)['NADPH'] == 12


