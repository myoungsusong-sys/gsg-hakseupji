HB_ANS = collections.Counter()


def HB(tid, d, head, items, pre=()):
    """<보기> 합답형 — items = [(진술, 참/거짓, 까닭), ...] 로 정답과 해설의 옳음/옳지 않음을 기계가 정한다."""
    assert len(items) == 3
    ans = ', '.join('ㄱㄴㄷ'[i] for i, (_, t, _r) in enumerate(items) if t)
    assert ans, head[:30]
    body = head + '\n\n<보기>\n' + '\n'.join(f'{"ㄱㄴㄷ"[i]}. {s}' for i, (s, _t, _r) in enumerate(items))
    steps = list(pre) + [f'{"ㄱㄴㄷ"[i]}: {r}({"옳음" if t else "옳지 않음"}).' for i, (_s, t, r) in enumerate(items)]
    HB_ANS[ans] += 1
    q(tid, d, body, ans, WR[ans], steps + [f'옳은 것은 {ans}이다.'])


def dec(x):
    """Fraction/float → 깔끔한 소수 문자열 (0.4, 1.92, 2)"""
    return f'{float(x):.4f}'.rstrip('0').rstrip('.')


