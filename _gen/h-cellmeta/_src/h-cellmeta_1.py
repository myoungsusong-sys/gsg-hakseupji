HB_ANS = collections.Counter()


def HB(tid, d, head, items, steps, want):
    """<보기> ㄱㄴㄷ 합답형 — items = [(진술, 참/거짓), ...] 로 정답을 기계가 정하고, 의도한 답(want)과 대조한다."""
    assert len(items) == 3 and len(steps) >= 3
    ans = ', '.join('ㄱㄴㄷ'[i] for i, (_, t) in enumerate(items) if t)
    assert ans == want, (tid, ans, want)
    body = head + '\n\n<보기>\nㄱ. ' + items[0][0] + '\nㄴ. ' + items[1][0] + '\nㄷ. ' + items[2][0]
    HB_ANS[ans] += 1
    Q(tid, d, body, ans, WR[ans], steps + [f'옳은 것은 {ans}이다.'])


def formula(*terms):
    """(계수, (C, H, O)) 들의 합 — 탈수 축합 분자식 검산용"""
    out = [0, 0, 0]
    for k, f in terms:
        for i in range(3):
            out[i] += k * f[i]
    return tuple(out)


