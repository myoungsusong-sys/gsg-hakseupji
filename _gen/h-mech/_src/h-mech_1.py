def eq(a, b, tol=1e-9):
    assert abs(a - b) <= tol * max(1.0, abs(b)), (a, b)


def Q(tid, d, body, ans, wrongs, steps):
    assert len(wrongs) == 4 and len(set([ans] + list(wrongs))) == 5, (tid, ans, wrongs)
    q(tid, d, body, ans, list(wrongs), steps)


ALL = ['ㄱ', 'ㄴ', 'ㄷ', 'ㄱ, ㄴ', 'ㄱ, ㄷ', 'ㄴ, ㄷ', 'ㄱ, ㄴ, ㄷ']
_gpos = [0] * 5


def G(tid, d, stem, items, expect, pre=(), post=()):
    """<보기> 합답형. items = [(진술, 참거짓, 판단 근거)] — 정답은 참거짓에서 자동으로 만들고 expect 와 대조한다.
    선지는 ㄱ…ㄱ,ㄴ,ㄷ 의 표준 순서에서 연속한 5개를 골라 순서대로 싣는다(정답 번호가 고르게 퍼지도록 창을 고른다)."""
    assert len(items) == 3
    lab = 'ㄱㄴㄷ'
    ans = ', '.join(lab[k] for k, it in enumerate(items) if it[1])
    assert ans == expect, (tid, ans, expect)
    i = ALL.index(ans)
    starts = [s for s in range(3) if s <= i <= s + 4]
    s = min(starts, key=lambda s: (_gpos[i - s], s))
    _gpos[i - s] += 1
    body = stem.rstrip() + '\n\n이에 대한 설명으로 옳은 것만을 <보기>에서 있는 대로 고른 것은?\n\n<보기>\n' + \
        '\n'.join(f'{lab[k]}. {it[0]}' for k, it in enumerate(items))
    steps = list(pre) + [f'{lab[k]}: {it[2]} → {"옳다" if it[1] else "옳지 않다"}.' for k, it in enumerate(items)] + list(post)
    qf(tid, d, body, ALL[s:s + 5], i - s, steps)


