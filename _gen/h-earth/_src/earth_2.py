def eq(a, b, tol=1e-9):
    assert abs(a - b) <= tol * max(1.0, abs(b)), (a, b)


def near(a, b, rel=0.03):
    """«약 ○» 로 쓴 값이 실제 계산값과 rel(기본 3 %) 안에서 맞는지"""
    assert abs(a - b) <= rel * abs(b), (a, b)


def Q(tid, d, body, ans, wrongs, steps):
    assert len(wrongs) == 4 and len(set([ans] + list(wrongs))) == 5, (tid, ans, wrongs)
    q(tid, d, body, ans, list(wrongs), steps)


STD = ['ㄱ', 'ㄷ', 'ㄱ, ㄴ', 'ㄴ, ㄷ', 'ㄱ, ㄴ, ㄷ']


def G(tid, d, stem, items, pre=(), post=()):
    """<보기> 합답형. items = [(진술, 참거짓(bool), 판단 근거)] — 정답 문자열은 참거짓에서 자동으로 만든다."""
    assert len(items) == 3
    lab = 'ㄱㄴㄷ'
    ans = ', '.join(lab[i] for i, it in enumerate(items) if it[1])
    assert ans, (tid, stem[:30])
    if ans in STD:
        wr = [c for c in STD if c != ans]
    elif ans == 'ㄴ':
        wr = ['ㄷ', 'ㄱ, ㄴ', 'ㄴ, ㄷ', 'ㄱ, ㄴ, ㄷ']
    else:  # 'ㄱ, ㄷ'
        wr = ['ㄱ', 'ㄱ, ㄴ', 'ㄴ, ㄷ', 'ㄱ, ㄴ, ㄷ']
    body = stem.rstrip() + '\n\n이에 대한 설명으로 옳은 것만을 <보기>에서 있는 대로 고른 것은?\n\n<보기>\n' + \
        '\n'.join(f'{lab[i]}. {it[0]}' for i, it in enumerate(items))
    steps = list(pre) + [f'{lab[i]}: {it[2]} → {"옳다" if it[1] else "옳지 않다"}.' for i, it in enumerate(items)] + list(post)
    Q(tid, d, body, ans, wr, steps)


