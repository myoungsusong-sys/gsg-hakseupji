SUP = str.maketrans('0123456789+-', '⁰¹²³⁴⁵⁶⁷⁸⁹⁺⁻')


def C(t):
    t = re.sub(r'\^(-?\d+[+\-]?|[+\-])', lambda m: m.group(1).translate(SUP), t)
    t = re.sub(r'(?<=[A-Za-z\)])([0-9]+)', lambda m: m.group(1).translate(SUB), t)
    return t


def ec(s):
    """'1s2 2s2 2p6' → '1s²2s²2p⁶'"""
    out = ''
    for tok in s.split():
        m = re.fullmatch(r'(\d)([spdf])(\d+)', tok)
        out += m.group(1) + m.group(2) + m.group(3).translate(SUP)
    return out


