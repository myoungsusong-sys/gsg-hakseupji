AM = {'H': Fr(1), 'C': Fr(12), 'N': Fr(14), 'O': Fr(16), 'Na': Fr(23), 'Mg': Fr(24), 'Al': Fr(27),
      'S': Fr(32), 'Cl': Fr(71, 2), 'K': Fr(39), 'Ca': Fr(40), 'Fe': Fr(56), 'Cu': Fr(64)}


def atoms(f):
    toks = re.findall(r'[A-Z][a-z]?|\d+|\(|\)', f)
    st = [collections.Counter()]
    i = 0
    while i < len(toks):
        t = toks[i]
        if t == '(':
            st.append(collections.Counter()); i += 1
        elif t == ')':
            g = st.pop(); i += 1; n = 1
            if i < len(toks) and toks[i].isdigit():
                n = int(toks[i]); i += 1
            for k, v in g.items():
                st[-1][k] += v * n
        else:
            i += 1; n = 1
            if i < len(toks) and toks[i].isdigit():
                n = int(toks[i]); i += 1
            st[-1][t] += n
    return st[0]


def M(f):
    return sum(AM[k] * v for k, v in atoms(f).items())


def bal(lhs, rhs):
    def tot(side):
        c = collections.Counter()
        for n, f in side:
            for k, v in atoms(f).items():
                c[k] += n * v
        return c
    return tot(lhs) == tot(rhs)


