_hc = [0]


def hap(tid, diff, stem, items, truth, expect, steps):
    """<보기> ㄱㄴㄷ 합답형 — 선지는 시험지 순서로 두고 정답 자리를 돌려 쓴다."""
    ans = ', '.join(k for k, t in zip('ㄱㄴㄷ', truth) if t)
    assert ans == expect, (tid, ans, expect)
    ci = HAP.index(ans)
    lo, hi = max(0, 4 - (6 - ci)), min(ci, 4)
    used = [sum(1 for p in lib._items if p.get('answer') == c) for c in '①②③④⑤']
    _hc[0] += 1
    t = min(range(lo, hi + 1), key=lambda i: (used[i], (i - _hc[0]) % 5))
    before = HAP[:ci][len(HAP[:ci]) - t:] if t else []
    after = HAP[ci + 1:][:4 - t]
    ch = before + [ans] + after
    assert len(ch) == 5 and ch.index(ans) == t
    body = stem + '\n\n<보기>\n' + '\n'.join(f'{k}. {x}' for k, x in zip('ㄱㄴㄷ', items))
    qf(tid, diff, body, ch, t, list(steps) + [f'옳은 것은 {ans}이다.'])


def qa(tid, diff, body, correct, wrongs, steps, pos):
    """정답 자리를 직접 정하는 객관식(정답 번호 고르게 맞추기용). 보기 순서에 의미는 없다."""
