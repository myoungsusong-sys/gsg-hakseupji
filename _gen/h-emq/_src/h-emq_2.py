def close(a, b, rel=1e-9):
    return abs(a - b) <= rel * max(abs(a), abs(b)) + 1e-300


def qn(tid, diff, body, correct, wrongs, steps, extra=()):
    """수치 선지 — (값, 표기) 쌍을 받아 값 오름차순으로 늘어놓는다(시험지처럼)."""
    wrongs = list(wrongs)
    if len(wrongs) < 4:
        used = [sum(1 for p in lib._items if p.get('answer') == c) for c in '①②③④⑤']
        best = None
        for combo in itertools.combinations(extra, 4 - len(wrongs)):
            idx = sorted([correct] + wrongs + list(combo), key=lambda x: x[0]).index(correct)
            key = (used[idx], extra.index(combo[0]) if combo else 0)
            if best is None or key < best[0]:
                best = (key, list(combo))
        wrongs = wrongs + best[1]
    assert len(wrongs) == 4
    allc = [correct] + list(wrongs)
    for i in range(5):
        for j in range(i + 1, 5):
            assert not close(allc[i][0], allc[j][0], 1e-6), (tid, body[:30], allc[i], allc[j])
    assert len({l for _, l in allc}) == 5
    order = sorted(allc, key=lambda x: x[0])
    qf(tid, diff, body, [l for _, l in order], order.index(correct), steps)


