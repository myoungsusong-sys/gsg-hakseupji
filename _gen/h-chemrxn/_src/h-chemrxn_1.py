def pH(h):
    return -math.log10(h)


def eq(a, b, tol=1e-9):
    return abs(a - b) <= tol * max(1.0, abs(a), abs(b))


def exact(c, k):
    """약산(약염기) c M, 이온화 상수 k 의 정확한 [H3O+]([OH-]) — 물의 자동 이온화 무시"""
    return (-k + math.sqrt(k * k + 4 * k * c)) / 2


def weak_p(c, k, expect):
    """근사식 √(ck) 로 구한 p값이 expect 와 같고, 정확한 값과 0.05 이내인지 확인"""
    a = -math.log10(math.sqrt(c * k))
    e = -math.log10(exact(c, k))
    assert abs(a - expect) < 1e-9 and abs(e - expect) < 0.05, (c, k, a, e)
    return a


def buf_pH(ka, ha, a):
    return pH(ka * ha / a)


def atoms(f):
    toks = re.findall(r'[A-Z][a-z]?|\d+|\(|\)', f)
    st = [collections.Counter()]
    i = 0
    while i < len(toks):
        t = toks[i]
        if t == '(':
            st.append(collections.Counter()); i += 1
        elif t == ')':
            g = st.pop(); i += 1; n = 1
            if i < len(toks) and toks[i].isdigit():
                n = int(toks[i]); i += 1
            for k, v in g.items():
                st[-1][k] += v * n
        else:
            i += 1; n = 1
            if i < len(toks) and toks[i].isdigit():
                n = int(toks[i]); i += 1
            st[-1][t] += n
    return st[0]


def side(s):
    at = collections.Counter(); ch = 0
    for term in s.split(' + '):
        term = re.sub(r'\((aq|g|s|l)\)$', '', term.strip())
        m = re.fullmatch(r'(\d*)([A-Za-z0-9()]+?)(?:\^(\d*)([+\-]))?', term)
        assert m, term
        n = int(m.group(1) or 1)
        f = m.group(2)
        z = 0
        if m.group(4):
            z = int(m.group(3) or 1) * (1 if m.group(4) == '+' else -1)
        if f != 'e':
            for k, v in atoms(f).items():
                at[k] += n * v
        ch += n * z
    return at, ch


def bal(s):
    """'2MnO4^- + 16H^+ + ... → ...' 원자 수·전하가 맞으면 True"""
    l, r = re.split(r' → | ⇌ ', s)
    return side(l) == side(r)


def ox(f, el, charge=0, known=None):
    """화학식 f 에서 원소 el 의 산화수(다른 원소 산화수는 known 으로)"""
    base = {'O': -2, 'H': 1, 'F': -1, 'Na': 1, 'K': 1, 'Li': 1, 'Ca': 2, 'Mg': 2, 'Ba': 2, 'Al': 3, 'Cl': -1}
    if known:
        base.update(known)
    a = atoms(f)
    rest = sum(base[k] * v for k, v in a.items() if k != el)
    return Fr(charge - rest, a[el])


