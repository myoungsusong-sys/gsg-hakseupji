def curve_sa(ca, va, cb, vb):
    """강산 ca M va mL 에 강염기 cb M vb mL 를 넣었을 때 pH (25 ℃)"""
    h = ca * va - cb * vb
    v = (va + vb) / 1000
    if abs(h) < 1e-12:
        return 7.0
    return pH(h / 1000 / v) if h > 0 else 14 - pH(-h / 1000 / v)


