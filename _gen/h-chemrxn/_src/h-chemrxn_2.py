def parse(f):
    """화학식(유니코드 아래·위 첨자) → (원소 개수, 전하)"""
    if f == 'e⁻':
        return collections.Counter(), -1
    charge = 0
    m = re.search(r'([⁰¹²³⁴⁵⁶⁷⁸⁹]*)([⁺⁻])$', f)
    if m:
        n = int(''.join(str(SUPS.index(c)) for c in m.group(1)) or '1')
        charge = n if m.group(2) == '⁺' else -n
        f = f[:m.start()]
    s = f.translate(str.maketrans(SUBS, '0123456789'))

    def grp(i):
        cnt = collections.Counter()
        while i < len(s):
            c = s[i]
            if c == '(':
                sub, i = grp(i + 1)
                j = i
                while j < len(s) and s[j].isdigit():
                    j += 1
                k = int(s[i:j]) if j > i else 1
                for e, v in sub.items():
                    cnt[e] += v * k
                i = j
            elif c == ')':
                return cnt, i + 1
            elif c.isupper():
                j = i + 1
                while j < len(s) and s[j].islower():
                    j += 1
                el = s[i:j]
                k0 = j
                while j < len(s) and s[j].isdigit():
                    j += 1
                cnt[el] += int(s[k0:j]) if j > k0 else 1
                i = j
            else:
                raise ValueError(f)
        return cnt, i
    return grp(0)[0], charge


def balanced(lhs, rhs):
    """[(계수, 화학식)] 양변의 원자 수·전하가 같은지"""
    def tot(side):
        c = collections.Counter(); ch = 0
        for k, f in side:
            a, z = parse(f)
            for e, v in a.items():
                c[e] += k * v
            ch += k * z
        return c, ch
    return tot(lhs) == tot(rhs)


