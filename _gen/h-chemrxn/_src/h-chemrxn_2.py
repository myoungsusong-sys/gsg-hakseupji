def V(x):
    """표준 환원 전위 표기(+0.80 V, −0.76 V)"""
    return ('+' if x > 0 else ('−' if x < 0 else '')) + '%.2f' % abs(x) + ' V'


def etab(rows):
    """[(반쪽 반응식, E°)] → 자료 줄"""
    return '\n'.join(f'· {r}   E° = {V(e)}' for r, e in rows)


