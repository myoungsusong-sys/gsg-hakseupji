def mm(f):
    """화학식량(Fraction)"""
    a, _ = parse(f)
    return sum(AM[e] * v for e, v in a.items())


def num(x):
    """깔끔한 숫자 문자열"""
    x = float(x)
    if abs(x - round(x)) < 1e-9:
        return str(int(round(x)))
    return ('%.4f' % x).rstrip('0').rstrip('.')


def cox(f):
    """유기 화합물 CxHyOz 의 탄소 평균 산화수"""
    a, z = parse(f)
    return Fr(z - a['H'] * 1 + a['O'] * 2, a['C'])


