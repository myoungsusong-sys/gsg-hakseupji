// 정답이 "텍스트로 채점할 수 없는" 문항을 가려낸다 → 호출부가 answer.png(정답 이미지)로 돌린다.
//
// 🔴 왜 중요한가: 여기서 빠뜨린 문항은 자동채점을 타고, 학생이 무엇을 써도 오답이 된다.
//    2026-08-13 '해설 참조' 누락으로 2,857건이 그 상태였고,
//    2026-09-12 전수 재점검에서 아래 ②③ 유형 2,493건이 같은 상태로 남아 있어 함께 막았다.
//    pool.ts / essay.ts 가 각자 판정하던 것을 이 파일로 합쳐 다시 어긋나지 않게 한다.

// ① 수집 단계에서 답이 비었다는 표시
const PLACEHOLDER = ['.', '-', '풀이참조', '해설 참조', '해설참조', '해설참고', '풀이 참조']

// ② 답 전체가 "그림의 어디"를 가리키는 말뿐인 경우 (표·그래프를 채우는 문항)
//    ⚠️ 부분 일치로 넓히면 안 된다 — '표본조사'·'위인전'·'아래로 볼록'·'오른쪽,아래쪽'은
//       모두 학생이 실제로 입력하는 정답이다. 그래서 **완전 일치**로만 막는다.
const POINTER_ONLY = new Set([
  '아래', '위', '왼쪽', '오른쪽', '아래[쪽]', '위[쪽]',
  '그림', '그래프', '표', '그림그래프', '그림 그래프',
])

// ③ 표 채우기형 — "[위에서부터] 500,120,5,…" 처럼 여러 칸을 한 줄에 몰아넣은 답
const TABLE_FILL = /^\[?(위에서부터|왼쪽에서부터|순서대로)/

export function isImageAnswer(ans: unknown): boolean {
  const a = String(ans ?? '').trim()
  if (!a) return true
  if (PLACEHOLDER.includes(a)) return true
  if (POINTER_ONLY.has(a)) return true
  if (TABLE_FILL.test(a)) return true
  // ※ 쉼표로 나열된 다중답(예: "5,6,7,8,9")은 그대로 둔다 —
  //    mathEqual이 순서 무관 비교·띄어쓰기 보정까지 하므로 자동채점이 정상 동작한다.
  return false
}
